"""
Generate ``static/css/backdrop.css``, the contour-line tiles of the backdrop.

The tiles come from the design system's Sphinx package, which draws the same
backdrop for the library docs. The seed is hashed into the terrain, so the
same seed always gives the same tiles. Run this only when the seed or the
package version changes::

    pip install "michel-albert-sphinx @ git+https://github.com/exhuma/michel-albert-sphinx@v0.5.0"
    python theme/generate_backdrop.py
"""

from importlib.metadata import version
from pathlib import Path

from michel_albert_sphinx import backdrop

SEED = "Michel Albert"
TARGET = Path(__file__).parent / "static" / "css" / "backdrop.css"


def svg_url(svg: str) -> str:
    """
    Return *svg* as a CSS ``url()`` with a percent-encoded data URI.
    """
    data = (
        svg.replace('"', "'")
        .replace("%", "%25")
        .replace("#", "%23")
        .replace("<", "%3C")
        .replace(">", "%3E")
    )
    return f'url("data:image/svg+xml,{data}")'


def main() -> None:
    """
    Write the tiles for :data:`SEED` to :data:`TARGET`.
    """
    lines, accent = backdrop.contour_tiles(SEED)
    TARGET.write_text(
        "/* Generated by theme/generate_backdrop.py from michel-albert-sphinx"
        f" {version('michel-albert-sphinx')},\n"
        f"   seed {SEED!r}. Do not edit by hand. */\n"
        ":root {\n"
        f"  --pattern: {svg_url(lines)};\n"
        f"  --pattern-accent: {svg_url(accent)};\n"
        "}\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
